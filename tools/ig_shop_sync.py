#!/usr/bin/env python3
"""Sync the Instagram grid on themuseshelf.com/shop/ (link-in-bio page) from the IG calendars.

  uv run --quiet --with pillow python tools/ig_shop_sync.py [SITE_ROOT]     (default: this script's site folder)

Reads ~/CamillaAmazon/instagram/calendar/*/plan.json, keeps posts with status posted or approved, copies each post's
cover (carousel = first slide, reel = cover) to src/assets/ig/<batch>_<n>.jpg (540x675) and rewrites the IG_POSTS
block in src/js/content.js. The /shop page shows a tile only once its scheduled time has passed (checked in the
visitor's browser), so approved posts can be synced ahead of time. Re-run (then build + deploy) after approving or
holding calendar posts.
"""
import datetime as dt
import json
import re
import sys
from pathlib import Path
from urllib.parse import urlparse
from zoneinfo import ZoneInfo

from PIL import Image, ImageOps

SITE = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path(__file__).resolve().parents[1]
IG = Path.home() / 'CamillaAmazon/instagram/calendar'
TZ = ZoneInfo('America/Chicago')
BEGIN, END = '/* IG_SHOP:BEGIN */', '/* IG_SHOP:END */'


def when(batch, date, time):
    year = int(batch[:4])
    d = dt.datetime.strptime(date, '%Y-%m-%d').date() if re.match(r'\d{4}-', date) else \
        dt.datetime.strptime(f'{date} {year}', '%a %b %d %Y').date()
    t = dt.datetime.strptime(time.strip().upper(), '%I:%M %p' if re.search(r'[AP]M', time, re.I) else '%H:%M').time()
    return dt.datetime.combine(d, t, TZ)


def main():
    content = SITE / 'src/js/content.js'
    js = content.read_text()
    # both post styles: slug: '...' and JSON-style "slug": "..." (guides, recipes); skip the generated IG block
    body = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), '', js, flags=re.S)
    slugs = set(re.findall(r"""["']?slug["']?\s*:\s*["']([^"']+)["']""", body))
    out_dir = SITE / 'src/assets/ig'
    out_dir.mkdir(parents=True, exist_ok=True)
    items, problems = [], []
    for plan_path in sorted(IG.glob('*/plan.json')):
        plan = json.loads(plan_path.read_text())
        batch = plan.get('batch') or plan_path.parent.name
        for p in plan['posts']:
            if p.get('status') not in ('posted', 'approved'):
                continue
            slug = urlparse(p.get('dm_link') or '').path.strip('/')
            if slug not in slugs:
                problems.append(f'{batch} #{p["n"]}: site post "{slug}" not found')
                continue
            src = p.get('cover') if p.get('format') == 'reel' else (p.get('media') or [None])[0]
            if not src or not (plan_path.parent / src).exists():
                problems.append(f'{batch} #{p["n"]}: cover image missing ({src})')
                continue
            name = f'{batch}_{p["n"]}.jpg'
            im = ImageOps.fit(Image.open(plan_path.parent / src).convert('RGB'), (540, 675), Image.LANCZOS)
            im.save(out_dir / name, quality=82, optimize=True, progressive=True)
            first = (p.get('caption') or '').split('\n')[0].strip()
            items.append({'at': when(batch, p['date'], p['time']).isoformat(), 'slug': slug,
                          'image': f'assets/ig/{name}', 'alt': first[:120], 'reel': p.get('format') == 'reel'})
    items.sort(key=lambda x: x['at'], reverse=True)
    block = (BEGIN + '\n/* Instagram grid for /shop/ (link in bio). Generated by tools/ig_shop_sync.py from the IG calendars:\n'
             '   do not edit by hand. A tile shows once its scheduled time (at) has passed. */\n'
             'var IG_POSTS = ' + json.dumps(items, ensure_ascii=False, indent=1) + ';\n' + END)
    if BEGIN in js:
        js = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda m: block, js, flags=re.S)
    else:
        js = js.replace('\nwindow.TMS = {', '\n' + block + '\n\nwindow.TMS = {', 1)
    if 'IG_POSTS: IG_POSTS' not in js:
        js = js.replace('window.TMS = {', 'window.TMS = { IG_POSTS: IG_POSTS,', 1)
    content.write_text(js)
    keep = {Path(i['image']).name for i in items}
    for f in out_dir.glob('*.jpg'):
        if f.name not in keep:
            f.unlink()
    print(json.dumps({'items': len(items), 'problems': problems}))


if __name__ == '__main__':
    main()
